#!/usr/bin/env python3
"""Collect the independent review remarks into REVIEW_LOG/.

The remarks are posted to the agent handoff issue (#31). Each one that
reviews a commit starts with a heading:

    ## Independent master review - <full sha>

This reads the issue's comments and writes them into the review log that
lives on the `feature/independent-review-log` branch:

  - `REVIEW_LOG/commits/<sha>.md` - one file per reviewed commit. A file
    that already exists is NEVER touched: a review entry is a piece of
    work, and the next run must not overwrite it.
  - `REVIEW_LOG/INDEX.md` - a table of every review seen, regenerated
    each run. It is the only file this writes unconditionally.
  - `REVIEW_LOG/BRANCH_COMMITS.md` - the branch's own commits. Entries
    are appended, never rewritten.

    python3 scripts/independent_review_log.py \
        --comments comments.json --log-dir REVIEW_LOG

Standard library only. Fails closed: malformed input is an error, not a
silently empty log.
"""

import argparse
import json
import os
import re
import subprocess
import sys

# The heading a review remark starts with. The dash is an em dash in the
# posted remarks, so all three are accepted.
HEADING = re.compile(
    r"^##\s+Independent master review\s*[—\-–]\s*([0-9a-f]{7,40})\s*$",
    re.MULTILINE,
)
FINDING = re.compile(r"^\*\*Finding[^*]*\*\*:?\s*(.*)$", re.MULTILINE)
SEVERITY = re.compile(r"\bP([0-3])\b")
STATUS = re.compile(
    r"\b(CONFIRMED|RISK\s*/\s*NEEDS VERIFICATION|NOT VERIFIED|NO FINDING)\b"
)
ISSUE_URL = "https://github.com/grep999/ramshield/issues/31"

INDEX_HEADER = """# Independent review index

Generated by `scripts/independent_review_log.py` from the remarks in the
agent handoff issue ([#31](%s)). Regenerated on the hour, so it is
rewritten each run. The per-commit entries under `commits/` are not
rewritten: a review entry is work, and only the index is a view of it.

""" % ISSUE_URL


def load_comments(path):
    """The issue's comments, as a list of dicts."""
    with open(path) as f:
        data = json.load(f)
    if not isinstance(data, list):
        raise ValueError("comments file must hold a JSON list")
    out = []
    for c in data:
        if not isinstance(c, dict):
            raise ValueError("a comment is not an object")
        out.append(c)
    return out


def parse(body):
    """One review out of a comment body, or None if it is not a review."""
    if not isinstance(body, str):
        return None
    m = HEADING.search(body)
    if not m:
        return None
    sha = m.group(1)
    tail = body[m.end():]
    # the title of the commit is the link text of the commit link
    title = ""
    link = re.search(
        r"\[([^\]]+)\]\(https://github\.com/[^)]+/commit/[^)]+\)", tail
    )
    if link:
        title = link.group(1)
    finding = ""
    f = FINDING.search(tail)
    if f:
        finding = " ".join(f.group(1).split())
    severity = ""
    s = SEVERITY.search(tail[:4000])
    if s:
        severity = "P" + s.group(1)
    status = ""
    st = STATUS.search(tail[:6000])
    if st:
        status = " ".join(st.group(1).split())
    return {
        "sha": sha,
        "title": title,
        "finding": finding,
        "severity": severity,
        "status": status,
    }


def collect(comments):
    """Every review in the comments, oldest first."""
    reviews = []
    for c in comments:
        r = parse(c.get("body", ""))
        if r is None:
            continue
        r["id"] = c.get("id")
        r["created_at"] = c.get("created_at", "") or ""
        r["url"] = "%s#issuecomment-%s" % (ISSUE_URL, c.get("id"))
        r["body"] = c.get("body", "") or ""
        r["created"] = r["created_at"]
        reviews.append(r)
    reviews.sort(key=lambda r: (r["created_at"], str(r["id"])))
    return reviews


def entry_text(review):
    """The per-commit review entry, from the remark it came from."""
    status = review["status"] or "NOT VERIFIED"
    return """# Review: `{sha}`

- **Commit:** {title}
- **Full SHA:** `{sha}`
- **Reviewed at:** {created}
- **Severity:** {severity}
- **Status:** {status}
- **Source:** [remark on issue #31]({url})

**Finding.** {finding}

## The remark, as posted

```
{body}
```
""".format(
        sha=review["sha"],
        title=review["title"] or "no title",
        created=review["created"] or "unknown",
        severity=review["severity"] or "not stated",
        status=status,
        url=review["url"],
        finding=review["finding"] or "not stated in the remark",
        body=review["body"].rstrip(),
    )


def index_text(reviews, log_dir):
    """The index, listing every review and whether it has an entry file."""
    lines = [INDEX_HEADER]
    lines.append("| reviewed commit | severity | status | entry | posted | source |")
    lines.append("|---|---|---|---|---|---|")
    for r in reviews:
        entry = os.path.join(log_dir, "commits", r["sha"] + ".md")
        have = os.path.isfile(entry)
        lines.append(
            "| `%s` | %s | %s | %s | %s | [remark](%s) |"
            % (
                r["sha"][:7],
                r["severity"] or "—",
                r["status"] or "—",
                ("[%s](commits/%s.md)" % (r["sha"][:7], r["sha"]))
                if have
                else "not yet written",
                (r["created_at"] or "—")[:19],
                r["url"],
            )
        )
    if not reviews:
        lines.append("| — | — | — | no review remarks yet | — | — |")
    lines.append("")
    return "\n".join(lines)


def write_if_absent(path, text):
    """Never overwrite. Returns True when the file was created."""
    if os.path.isfile(path):
        return False
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    return True


def write_if_changed(path, text):
    """Write only when the content differs. Returns True when written."""
    if os.path.isfile(path):
        with open(path) as f:
            if f.read() == text:
                return False
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    return True


def branch_commits(repo):
    """The branch's own commits, oldest first, as dicts.

    The files each commit touched are read from git, so the log entry
    says what actually changed instead of guessing.
    """
    try:
        out = subprocess.check_output(
            [
                "git", "log", "--reverse",
                "--format=%H%x1f%P%x1f%s",
                "origin/master..HEAD",
            ],
            cwd=repo, stderr=subprocess.DEVNULL,
        ).decode()
    except Exception:
        return []
    commits = []
    for line in out.splitlines():
        parts = line.split("\x1f")
        if len(parts) != 3:
            continue
        sha = parts[0]
        commits.append({
            "sha": sha,
            "parent": parts[1].split()[0] if parts[1] else "",
            "message": parts[2],
            "files": changed_files(repo, sha),
        })
    return commits


def changed_files(repo, sha):
    """The files a commit touched, one per line."""
    try:
        out = subprocess.check_output(
            ["git", "show", "--name-only", "--format=", sha],
            cwd=repo, stderr=subprocess.DEVNULL,
        ).decode()
    except Exception:
        return []
    return [l for l in out.splitlines() if l.strip()]


def append_branch_commits(path, commits):
    """Append the branch commits that are not logged yet. Never rewrites."""
    if not os.path.isfile(path):
        return 0
    with open(path) as f:
        text = f.read()
    if not text.endswith("\n"):
        # the file may end mid-line; a new entry needs a line of its own
        text += "\n"
    added = 0
    number = text.count("\n### ")
    for c in commits:
        if c["sha"] in text:
            continue
        number += 1
        files = c.get("files") or []
        files_label = ("`%s`" % "`, `".join(files)) if files else "no files reported"
        text += """
### %d. `%s`

- **Parent/base:** `%s`
- **Message:** `%s`
- **Path:** %s
- **Purpose:** recorded by the collector; what it did is in the message.
- **Validation:** not validated. The commit was recorded by the
  collector, not reviewed; no test, build or CI check was run for it.
""" % (
            number,
            c["sha"],
            c["parent"],
            c["message"],
            files_label,
        )
        added += 1
    if added:
        with open(path, "w") as f:
            f.write(text)
    return added


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--comments", required=True, help="the issue's comments, as JSON")
    ap.add_argument("--log-dir", default="REVIEW_LOG", help="the review log directory")
    ap.add_argument("--repo", default=".", help="the repository, for the branch log")
    args = ap.parse_args()

    comments = load_comments(args.comments)
    reviews = collect(comments)

    created = 0
    for r in reviews:
        path = os.path.join(args.log_dir, "commits", r["sha"] + ".md")
        if write_if_absent(path, entry_text(r)):
            created += 1

    index = os.path.join(args.log_dir, "INDEX.md")
    index_written = write_if_changed(index, index_text(reviews, args.log_dir))

    branch = append_branch_commits(
        os.path.join(args.log_dir, "BRANCH_COMMITS.md"),
        branch_commits(args.repo),
    )

    print("reviews: %d  entries written: %d  index: %s  branch entries: %d"
          % (len(reviews), created,
             "written" if index_written else "unchanged", branch))
    for r in reviews:
        print("  %s %s %s" % (r["sha"][:7], r["severity"] or "-", r["title"][:60]))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as e:  # noqa: BLE001 - the workflow wants a clear failure
        print("independent_review_log: %s" % e, file=sys.stderr)
        sys.exit(1)
